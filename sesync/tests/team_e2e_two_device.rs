//! The permanent two-device end-to-end test: a real team-server process, a real Postgres, and the
//! daemon's own sealing and pulling code. One device seals a session for both, the server stores
//! it without ever seeing the text, and the other device pulls it back verified. Runs only when
//! TEAM_TEST_PG and TEAM_SERVER_BIN are set; in CI TEAM_REQUIRE_PG makes a skip a failure.
use sesync::device_keys::load_or_create;
use sesync::sealed::seal_for_devices;
use sesync::team_join;
use sesync::team_push::{HttpTeam, TeamRemote};
use sesync::team_watch::TeamWatch;
use sesync_team::pg::PgStore;
use sesync_team::service::Service;
use sesync_team::totp::code_at;
use std::collections::BTreeMap;
use std::process::{Child, Command, Stdio};
use std::time::Duration;

const MASTER: [u8; 32] = [5u8; 32];
/// The server disables admin routes for tokens shorter than 32 chars, so this is long on purpose.
const ADMIN_TOKEN: &str = "e2e-admin-token-000000000000000000000000";

struct Server(Child);
impl Drop for Server {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// Skip politely without a database and the server binary; refuse to skip in CI.
fn live_env() -> Option<(String, String)> {
    match (std::env::var("TEAM_TEST_PG"), std::env::var("TEAM_SERVER_BIN")) {
        (Ok(pg), Ok(bin)) => Some((pg, bin)),
        _ => {
            if std::env::var("TEAM_REQUIRE_PG").is_ok() {
                panic!("TEAM_REQUIRE_PG is set but this test needs TEAM_TEST_PG and TEAM_SERVER_BIN");
            }
            eprintln!("skipped: set TEAM_TEST_PG and TEAM_SERVER_BIN");
            None
        }
    }
}

fn wait_health(port: u16) {
    let agent = ureq::AgentBuilder::new().timeout(Duration::from_secs(2)).build();
    for _ in 0..75 {
        if agent.get(&format!("http://127.0.0.1:{port}/healthz")).call().is_ok() {
            return;
        }
        std::thread::sleep(Duration::from_millis(200));
    }
    panic!("the team server did not come up");
}

#[test]
fn two_devices_share_a_session_through_a_real_server() {
    let Some((pg, bin)) = live_env() else { return };
    let schema = "t_two_device";
    let mut client = postgres::Client::connect(&pg, postgres::NoTls).unwrap();
    client
        .batch_execute(&format!("DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema};"))
        .unwrap();
    let scoped = format!("{pg}?options=-c%20search_path%3D{schema}");
    let store = PgStore::connect(&scoped, MASTER).unwrap();
    store.migrate().unwrap();

    let dir = std::env::temp_dir().join(format!("sesync-two-device-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("master.key"), MASTER).unwrap();
    std::fs::write(dir.join("admin.token"), ADMIN_TOKEN).unwrap();

    // The writer's device identity. The admin key is generated by the CLI at `team create`,
    // and the reader's device is generated by `team join`.
    let writer = load_or_create(&dir.join("keys/writer")).unwrap();

    // The real server, bound to a throwaway port and schema.
    let port = 18600 + (std::process::id() % 400) as u16;
    let log = std::fs::File::create(dir.join("server.log")).unwrap();
    let child = Command::new(&bin)
        .env("TEAM_SERVER_BIND", format!("127.0.0.1:{port}"))
        .env("TEAM_SERVER_DATABASE", &scoped)
        .env("TEAM_MASTER_KEY_FILE", dir.join("master.key"))
        .env("TEAM_ADMIN_TOKEN_FILE", dir.join("admin.token"))
        .stdout(Stdio::null())
        .stderr(Stdio::from(log))
        .spawn()
        .expect("start team-server");
    let _server = Server(child);
    wait_health(port);
    let base = format!("http://127.0.0.1:{port}");

    // The admin creates the team through the daemon's own CLI: an admin key is generated here,
    // the server pins its public half and can never forge a list.
    let admin_cmd = sesync::team_cli::Command::Create {
        name: "personal".into(),
        members: vec!["writer".into(), "reader".into()],
    };
    let (text, _uri) = sesync::team_cli::run_detailed(&admin_cmd, &base, ADMIN_TOKEN, &dir)
        .expect("the admin creates the team");
    assert!(text.contains("team 'personal' created"), "{text}");
    assert!(dir.join("admin/device.key").exists(), "the admin key lives on this machine");

    // Both member devices enrol with the team code, through the daemon's own join code. Each
    // machine's join config is the directory holding its device key, so the device the join
    // binds is the one the admin's list names.
    let now = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_secs();
    let svc = Service::new(PgStore::connect(&scoped, MASTER).unwrap());
    let code = code_at(&svc.space_secret("personal").unwrap(), now);
    let writer_path = team_join::join(&base, "personal", "writer", "writer-box", &code, &dir.join("keys/writer")).unwrap();
    let reader_path = team_join::join(&base, "personal", "reader", "reader-box", &code, &dir.join("keys/reader")).unwrap();
    let writer_cred = team_join::load(&writer_path).unwrap();
    let reader_cred = team_join::load(&reader_path).unwrap();
    let pinned = team_join::trust_of(&reader_cred).expect("the join pinned the trust root");

    // The admin signs the enrolled devices into the member list: publish is the step that makes
    // a joining device a member.
    let publish = sesync::team_cli::Command::Publish { name: "personal".into() };
    let (text, _) = sesync::team_cli::run_detailed(&publish, &base, ADMIN_TOKEN, &dir).unwrap();
    assert!(text.contains("published list v2"), "the joins become members: {text}");

    // The writer catches up to the published list before sealing: records must be signed under
    // the current list version, so revocation stays meaningful.
    let sealed_trust = sesync::team_watch::fetch_and_verify(
        &base, &writer_cred.token, "writer-box", "personal", &pinned)
        .expect("the writer catches up to the published list");

    // The writer takes the lease first: the record's sequence is the lease version. It seals the
    // session for the listed devices under that version and stores it.
    let text = b"the two-device session\n".to_vec();
    let team = HttpTeam { base: base.clone(), token: writer_cred.token.clone(), machine: "writer-box".into() };
    let version = team.acquire("personal", "ses_live").unwrap();
    let record = seal_for_devices(&writer, &sealed_trust, "personal", "ses_live", version, &text).unwrap();
    team.put_to("/record/sealed", "personal", "ses_live", version, &record).unwrap();
    team.release("personal", "ses_live").unwrap();

    // The server holds bytes it cannot read: the session text does not appear in them.
    let row = client
        .query_one(
            &format!("SELECT position(convert_to($1, 'UTF8') IN sealed) FROM {schema}.records WHERE conversation = 'ses_live'"),
            &[&String::from_utf8(text.clone()).unwrap()],
        )
        .unwrap();
    let position: i32 = row.get(0);
    assert_eq!(position, 0, "the server must hold no plaintext copy of the session");

    // The reader pulls it back: verified against the admin-signed list the join pinned, shown,
    // nothing dropped.
    let watch = TeamWatch {
        base: base.clone(),
        token: reader_cred.token.clone(),
        machine: "reader-box".into(),
        space: "personal".into(),
        device: load_or_create(&dir.join("keys/reader")).unwrap(),
        trust: Some(pinned),
    };
    let out = watch.pull(&BTreeMap::new());
    assert_eq!(out.dropped, 0, "the writer is a listed author, so nothing is dropped");
    assert_eq!(out.shown.len(), 1, "the one stored session is shown");
    assert_eq!(out.shown[0].conversation, "ses_live");
    assert_eq!(out.shown[0].text, text, "the reader sees exactly what the writer sealed");

    // The admin revokes the writer: forget its device, then sign the next list. The reader's
    // pull catches up to the current list on its own, and the writer's stored session is
    // dropped and counted, never shown. A device that pinned the old list cannot be rolled
    // back: the newer, admin-signed list is the one used.
    let forget = sesync::team_cli::Command::Forget { name: "personal".into(), machine: "writer-box".into() };
    sesync::team_cli::run_detailed(&forget, &base, ADMIN_TOKEN, &dir).unwrap();
    let (text, _) = sesync::team_cli::run_detailed(&publish, &base, ADMIN_TOKEN, &dir).unwrap();
    assert!(text.contains("published list v3"), "the revocation is signed: {text}");

    let watch = TeamWatch {
        base: base.clone(),
        token: reader_cred.token.clone(),
        machine: "reader-box".into(),
        space: "personal".into(),
        device: load_or_create(&dir.join("keys/reader")).unwrap(),
        trust: team_join::trust_of(&reader_cred),
    };
    let out = watch.pull(&BTreeMap::new());
    assert_eq!(out.shown.len(), 0, "a revoked author is never shown");
    assert_eq!(out.dropped, 1, "and it is counted, not silently ignored");

    // The daemon's own --watch wiring runs the same pull, sandboxed away from the real install.
    let sandbox = dir.join("daemon");
    let out = Command::new(env!("CARGO_BIN_EXE_sesync"))
        .arg("--watch")
        .env("HOME", sandbox.join("home"))
        .env("SESYNC_DIR", sandbox.join("state"))
        .env("SESYNC_LOCK", sandbox.join("no-sesync_lock"))
        .env("SESYNC_LOCK_DIR", sandbox.join("locks"))
        .env("OMP_AGENT_DIR", sandbox.join("omp"))
        .env("PI_AGENT_DIR", sandbox.join("pi"))
        .env("CLAUDE_CONFIG_DIR", sandbox.join("claude"))
        .env("GEMINI_CLI_HOME", sandbox.join("gemini"))
        .env("OPENCODE_DB", sandbox.join("no-opencode").join("opencode.db"))
        .env("SESYNC_TEAM_URL", &base)
        .env("SESYNC_TEAM_TOKEN", &reader_cred.token)
        .env("SESYNC_TEAM_MACHINE", "reader-box")
        .env("SESYNC_TEAM_SPACE", "personal")
        .env("SESYNC_PASSES", "1")
        .env("SESYNC_POLL", "0")
        .output()
        .expect("run sesync --watch");
    assert!(out.status.success(), "the daemon exits cleanly: {}", String::from_utf8_lossy(&out.stderr));
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("team pull:"), "the watch loop reports its team pull: {stderr}");
    assert!(sandbox.join("state").join("state.json").exists(), "the daemon ran in the sandbox state dir, not the real one");

    let _ = std::fs::remove_dir_all(&dir);
}
